function buildShapeFromStopIds(stopIds: string[]): Array<{ lat: number; lng: number }> {
  return stopIds
    .map((id) => STOP_BY_ID[id])
    .filter(Boolean)
    .map((s) => ({ lat: s.stop_lat, lng: s.stop_lng }));
}

