const HIGH_TRAFFIC_CORRIDOR_ROUTES = new Set(['RT_405', 'RT_543', 'RT_534', 'RT_502']);
const SPARSE_DEMO_ROUTES = new Set(['RT_347', 'RT_729']);

function hashSeed(input: string): number {
  let h = 2166136261;
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h);
}

export function buildDemoSegmentCrowding(
  route: Route,
  directionId: 0 | 1,
  fromStopId: string,
  toStopId: string,
  timeBand: TimeBand,
  dayType: DayType
): CrowdingEstimate {
  const seed = hashSeed(`${route.route_id}:${directionId}:${fromStopId}:${toStopId}:${timeBand}:${dayType}`);
  const bandFactor = TIME_BAND_META[timeBand].multiplier;
  const dayFactor = dayType === 'weekday' ? 1.0 : 0.72;
  const isSparse = SPARSE_DEMO_ROUTES.has(route.route_id) || route.direction_status === 'ambiguous';
  const isLateOrSparseEdge = isSparse && (timeBand === 'late_evening' || timeBand === 'early_morning' || seed % 5 === 0);

  if (isLateOrSparseEdge) {
    return {
      crowdingLevel: 'insufficient_data',
      estimateType: 'insufficient_data',
      confidence: {
        level: 'insufficient_data',
        explanation:
          'Insufficient historical records: fewer than minimum sample observations or ambiguous direction matching for this time band.',
        evidence: {
          observationsCount: 4 + (seed % 7),
          routeMatchingQuality: route.direction_status === 'ambiguous' ? 'low' : 'medium',
          stopMatchingQuality: 'medium',
          directionMatchingQuality: route.direction_status === 'ambiguous' ? 'low' : 'medium',
          historicalCoverageLabel: '4 of 31 sample days observed',
          demandVariability: 'high',
          modelValidationStatus: 'not_evaluated',
          dataFreshness: 'Sample snapshot (Oct cycle)',
        },
      },
      coverage: {
        sampleCount: 4 + (seed % 7),
        daysObserved: 4,
        expectedDays: 31,
        coverageLabel: '4 / 31 days (sparse)',
        sufficientForRanking: false,
      },
      timeBand,
      dayType,
      observedTicketingDemand: null,
      reconstructedPassengerLoad: null,
      predictedDemand: null,
      verifiedVehicleCapacity: null,
      occupancyRatioPercent: null,
      relativeDemandIndexLabel: 'Insufficient evidence for relative demand classification',
      dataFreshness: 'Demonstration snapshot · Oct sample cycle',
      disclaimer: DEMO_DATASET_METADATA.disclaimer,
      isDemo: true,
    };
  }

  const baseRouteLoad = HIGH_TRAFFIC_CORRIDOR_ROUTES.has(route.route_id) ? 38 : 26;
  const hubBonus =
    fromStopId === 'DL_STP_004' ||
    fromStopId === 'DL_STP_011' ||
    fromStopId === 'DL_STP_014' ||
    toStopId === 'DL_STP_004' ||
    toStopId === 'DL_STP_011'
      ? 12
      : 0;

  // Deterministic variance per segment so Fastest vs Least Crowded genuinely differentiates routes
  const routeContrastOffset =
    route.route_id === 'RT_620' || route.route_id === 'RT_85EXT' ? -7 : route.route_id === 'RT_543' ? 8 : 0;

  const rawScore = Math.max(
    6,
    Math.round((baseRouteLoad + hubBonus + routeContrastOffset + (seed % 14)) * bandFactor * dayFactor)
  );

  let crowdingLevel: CrowdingLevel = 'low';
  if (rawScore >= 58) crowdingLevel = 'very_high';
  else if (rawScore >= 42) crowdingLevel = 'high';
  else if (rawScore >= 24) crowdingLevel = 'moderate';
  else crowdingLevel = 'low';

  const modeMod = seed % 3;
  let estimateType: EstimateType = 'observed_ticketing';
  if (route.direction_status === 'verified' && modeMod === 0) {
    estimateType = 'reconstructed_load';
  } else if (modeMod === 1) {
    estimateType = 'model_predicted';
  } else {
    estimateType = 'observed_ticketing';
  }

  const obsCount = isSparse ? 22 + (seed % 18) : 95 + (seed % 160);
  const daysObs = isSparse ? 11 + (seed % 7) : 23 + (seed % 8);
  let confLevel: ConfidenceLevel = 'high';
  if (isSparse || route.direction_status === 'partial') {
    confLevel = obsCount > 60 ? 'medium' : 'low';
  } else if (estimateType === 'model_predicted' && timeBand === 'evening_peak') {
    confLevel = 'medium';
  }

  const verifiedCapacity =
    estimateType === 'reconstructed_load' && route.agency_id === 'DTC' ? (route.is_ac ? 45 : 52) : null;
  const reconstructedLoad =
    estimateType === 'reconstructed_load' ? Math.min(68, Math.round(rawScore * 0.92)) : null;
  const occupancyRatio =
    reconstructedLoad !== null && verifiedCapacity !== null
      ? Math.round((reconstructedLoad / verifiedCapacity) * 100)
      : null;

  const relativeLabelMap: Record<CrowdingLevel, string> = {
    low: 'Relative historical demand: Low (bottom quartile in sample cycle)',
    moderate: 'Relative historical demand: Moderate (mid-range segment volume)',
    high: 'Relative historical demand: High (upper-tier peak segment volume)',
    very_high: 'Relative historical demand: Very High (top decile corridor volume)',
    insufficient_data: 'Insufficient data',
  };

  const confExplanation =
    confLevel === 'high'
      ? 'High confidence (demo): consistent GTFS route/stop match, verified direction, and dense historical sample coverage.'
      : confLevel === 'medium'
      ? 'Medium confidence (demo): sufficient historical ticketing records are available, but vehicle-level or direction matching is partial.'
      : 'Low confidence (demo): limited historical sample days or higher demand variability across observed trips.';

  return {
    crowdingLevel,
    estimateType,
    confidence: {
      level: confLevel,
      explanation: confExplanation,
      evidence: {
        observationsCount: obsCount,
        routeMatchingQuality: route.direction_status === 'verified' ? 'high' : 'medium',
        stopMatchingQuality: 'high',
        directionMatchingQuality: route.direction_status === 'verified' ? 'high' : 'medium',
        historicalCoverageLabel: `${daysObs} of 31 sample days observed`,
        demandVariability: crowdingLevel === 'very_high' ? 'high' : crowdingLevel === 'high' ? 'moderate' : 'low',
        modelValidationStatus: estimateType === 'model_predicted' ? 'evaluated_demo' : 'baseline_only',
        dataFreshness: 'Sample snapshot (Oct cycle)',
      },
    },
    coverage: {
      sampleCount: obsCount,
      daysObserved: daysObs,
      expectedDays: 31,
      coverageLabel: `${daysObs} / 31 days (${Math.round((daysObs / 31) * 100)}%)`,
      sufficientForRanking: confLevel === 'high' || confLevel === 'medium',
    },
    timeBand,
    dayType,
    observedTicketingDemand: rawScore,
    reconstructedPassengerLoad: reconstructedLoad,
    predictedDemand: estimateType === 'model_predicted' ? Math.round(rawScore * 1.04) : null,
    verifiedVehicleCapacity: verifiedCapacity,
    occupancyRatioPercent: occupancyRatio,
    relativeDemandIndexLabel: relativeLabelMap[crowdingLevel],
    dataFreshness: 'Demonstration snapshot · Oct sample cycle',
    disclaimer: DEMO_DATASET_METADATA.disclaimer,
    isDemo: true,
  };
}

export function buildAllDemoSegmentRows(): SegmentAnalyticsRow[] {
  const rows: SegmentAnalyticsRow[] = [];
  const timeBands: TimeBand[] = ['morning_peak', 'midday', 'evening_peak'];
  for (const route of DEMO_ROUTES) {
    const stops = route.stops_direction_0;
    for (let i = 0; i < stops.length - 1; i++) {
      const fromStop = STOP_BY_ID[stops[i]];
      const toStop = STOP_BY_ID[stops[i + 1]];
      if (!fromStop || !toStop) continue;
      for (const tb of timeBands) {
        const est = buildDemoSegmentCrowding(route, 0, fromStop.stop_id, toStop.stop_id, tb, 'weekday');
        rows.push({
          segmentId: `${route.route_id}_0_${fromStop.stop_id}_${toStop.stop_id}_${tb}`,
          routeId: route.route_id,
          routeShortName: route.route_short_name,
          directionId: 0,
          directionLabel: route.direction_0_label,
          fromStopId: fromStop.stop_id,
          fromStopName: fromStop.stop_name,
          toStopId: toStop.stop_id,
          toStopName: toStop.stop_name,
          timeBand: tb,
          dayType: 'weekday',
          observedTicketingDemand: est.observedTicketingDemand,
          reconstructedPassengerLoad: est.reconstructedPassengerLoad,
          predictedDemand: est.predictedDemand,
          crowdingLevel: est.crowdingLevel,
          confidence: est.confidence,
          sampleCount: est.coverage.sampleCount,
          coveragePercent: Math.round((est.coverage.daysObserved / est.coverage.expectedDays) * 100),
          estimateType: est.estimateType,
          isDemo: true,
        });
      }
    }
  }
  return rows;
}

